function midRange(s) {
  if (s == null) return null
  const t = String(s).replace(/~/g, '').replace(/утро\s*/i, '')
  const m = t.match(/(\d+(?:\.\d+)?)\s*[–\-]\s*(\d+(?:\.\d+)?)/)
  if (m) return (Number(m[1]) + Number(m[2])) / 2
  const one = t.match(/(\d+(?:\.\d+)?)/)
  return one ? Number(one[1]) : null
}

